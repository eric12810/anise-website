import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const source = readFileSync(new URL('../basket-storage.js', import.meta.url), 'utf8');
const values = new Map();
const localStorage = {getItem:key => values.get(key) ?? null, setItem:(key,value) => values.set(key,value), removeItem:key => values.delete(key)};
const window = {localStorage};
vm.runInNewContext(source, {window, Date});
const storage = window.AniseBasketStorage;
const menu = [{products:[{id:'p1',name:'Dish',variants:[{id:'v1',name:'Regular',price:8}],
  modifierGroups:[{minimumSelections:1,maximumSelections:1,modifiers:[{id:'m1',name:'Extra',priceAdjustment:2}]}]}]}];
const item = {productId:'p1',variantId:'v1',quantity:2,modifiers:[{id:'m1'}],notes:'',price:10};
assert.equal(storage.write([item],'Delivery'),true);
assert.equal(storage.read().orderType,'Delivery');
assert.equal(storage.read().items[0].quantity,2);
assert.equal(storage.read().expiresAt > Date.now()+6*86400000,true);
let restored = storage.resolve(storage.read(),menu);
assert.equal([...restored.entries.values()][0].price,10);
assert.equal(restored.notices.length,0);
menu[0].products[0].variants[0].price = 9;
restored = storage.resolve(storage.read(),menu);
assert.equal([...restored.entries.values()][0].price,11);
assert.match(restored.notices[0],/new price/);
assert.equal(storage.resolve(storage.read(),[]).entries.size,0);
assert.match(storage.resolve(storage.read(),[]).notices[0],/no longer available/);
menu[0].products[0].modifierGroups[0].modifiers = [];
assert.equal(storage.resolve(storage.read(),menu).entries.size,0);
assert.match(storage.resolve(storage.read(),menu).notices[0],/modifier/);
assert.equal(storage.clearIfMatches([{variantId:'v1',quantity:1,modifierIds:['m1'],notes:''}],'Delivery'),false);
assert.equal(storage.clearIfMatches([{variantId:'v1',quantity:2,modifierIds:['m1'],notes:''}],'Delivery'),true);
assert.equal(storage.read(),null);
// A second tab receives the stored payload without a customer account or session state.
storage.write([item],'Collection');
const secondWindow = {localStorage};
vm.runInNewContext(source, {window:secondWindow, Date});
assert.equal(secondWindow.AniseBasketStorage.read().items[0].variantId,'v1');
storage.clear();
values.set(storage.key,'{broken');
assert.equal(storage.read(),null);
values.set(storage.key,JSON.stringify({version:2,expiresAt:Date.now()+1000,orderType:'Collection',items:[]}));
assert.equal(storage.read(),null);
values.set(storage.key,JSON.stringify({version:1,expiresAt:Date.now()-1,orderType:'Collection',items:[]}));
assert.equal(storage.read(),null);
window.localStorage = {getItem(){throw Error('blocked')},setItem(){throw Error('blocked')},removeItem(){throw Error('blocked')}};
assert.equal(storage.read(),null);
assert.equal(storage.write([item],'Collection'),false);
storage.clear();
console.log('Passed basket storage checks.');
